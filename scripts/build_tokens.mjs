#!/usr/bin/env node
// Writes web/src/styles/tokens.css (CSS custom properties) from design/tokens.json.
// Plain Node, no dependencies. Run from anywhere: node scripts/build_tokens.mjs
// Naming: --wp-<group>-<key with _ as ->, e.g. color.ink_muted -> --wp-color-ink-muted.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const src = resolve(root, "design/tokens.json");
const out = resolve(root, "web/src/styles/tokens.css");
const tokens = JSON.parse(readFileSync(src, "utf8"));

const kebab = (s) => s.replace(/_/g, "-");
const PX_GROUPS = new Set(["shape"]);
const PX_KEYS = /^(size_|tick_size|label_size|title_size|line_width|marker_size|bar_)/;

function cssValue(group, key, value) {
  if (Array.isArray(value)) return null; // arrays become numbered variables below
  if (typeof value === "number") {
    if (PX_GROUPS.has(group) || (group === "type" && key.startsWith("size_")) || (group === "chart" && PX_KEYS.test(key))) {
      return `${value}px`;
    }
    return String(value);
  }
  if (typeof value === "boolean") return value ? "1" : "0";
  return String(value);
}

const lines = [];
const emit = (name, value, use) => {
  lines.push(`  --wp-${name}: ${value};${use ? ` /* ${use.replace(/\*\//g, "")} */` : ""}`);
};

for (const group of ["color", "type", "shape", "elevation", "chart"]) {
  const entries = tokens[group] ?? {};
  lines.push(`\n  /* ${group} */`);
  for (const [key, entry] of Object.entries(entries)) {
    const value = entry && typeof entry === "object" && "value" in entry ? entry.value : entry;
    const use = entry?.use ? entry.use.split(". ")[0] : "";
    if (Array.isArray(value)) {
      if (group === "chart" && key === "benchmark_dash") emit(`chart-benchmark-dash`, value.join(" "), use);
      else value.forEach((v, i) => emit(`${group}-${kebab(key)}-${i + 1}`, PX_GROUPS.has(group) ? `${v}px` : v));
      continue;
    }
    emit(`${group}-${kebab(key)}`, cssValue(group, key, value), use);
  }
}

// Scales: numbered stops plus their label inks.
for (const [name, scale] of Object.entries(tokens.scale ?? {})) {
  if (!Array.isArray(scale.stops)) continue;
  lines.push(`\n  /* scale.${name}: ${scale.use.split(". ")[0]} */`);
  scale.stops.forEach((hex, i) => emit(`scale-${name}-${i + 1}`, hex, scale.labels?.[i]));
  scale.label_ink?.forEach((hex, i) => emit(`scale-${name}-ink-${i + 1}`, hex));
}

const css = `/* Generated by scripts/build_tokens.mjs from design/tokens.json. Do not edit by hand. */
:root {${lines.join("\n")}
}
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`tokens: wrote ${out.replace(root, ".")} (${lines.filter((l) => l.includes("--wp-")).length} variables)`);

// The same values as a typed module, for code that needs raw values (Recharts props, canvas).
const valuesOnly = (group) =>
  Object.fromEntries(Object.entries(tokens[group] ?? {}).map(([k, e]) => [k, e && typeof e === "object" && "value" in e ? e.value : e]));
const scales = Object.fromEntries(
  Object.entries(tokens.scale ?? {}).map(([k, s]) => {
    const { use, ...rest } = s; // eslint-disable-line no-unused-vars
    return [k, rest];
  }),
);
const tsOut = resolve(root, "web/src/styles/tokens.ts");
const ts = `// Generated by scripts/build_tokens.mjs from design/tokens.json. Do not edit by hand.
export const tokens = ${JSON.stringify(
  { color: valuesOnly("color"), type: valuesOnly("type"), shape: valuesOnly("shape"), chart: valuesOnly("chart"), scale: scales },
  null,
  2,
)} as const;

export type ColorRole = keyof typeof tokens.color;
`;
writeFileSync(tsOut, ts);
console.log(`tokens: wrote ${tsOut.replace(root, ".")}`);
